CREATE TABLE Status (
    id INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    designation VARCHAR2(25 CHAR) NOT NULL UNIQUE,
    hourQuota INTEGER NOT NULL
);

CREATE TABLE Transportation (
    id INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    designation VARCHAR2(25 CHAR) NOT NULL UNIQUE
);

CREATE TABLE City (
    id INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    designation VARCHAR2 (50 CHAR) NOT NULL,
    postalCode NUMBER(4) NOT NULL
);

CREATE TABLE Location (
    id INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    designation VARCHAR2(50 CHAR),
    city INTEGER NOT NULL REFERENCES City(id) ON DELETE CASCADE,
    street VARCHAR2(50 CHAR) NOT NULL,
    streetNumber VARCHAR2(8 CHAR),
    box INTEGER
);

CREATE TABLE AppliUserT (
    id INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    begin DATE NOT NULL,
    end DATE,
    login VARCHAR2(7 CHAR),
    firstName VARCHAR2(25 CHAR) NOT NULL,
    lastName VARCHAR2(25 CHAR) NOT NULL,
    birthDate DATE NOT NULL,
    hashedPassword VARCHAR2(255 CHAR) NOT NULL,
    email VARCHAR2(50 CHAR) NOT NULL,
    phoneNumber VARCHAR2(25 CHAR)
);

CREATE TABLE InterpreterT (
    id INTEGER PRIMARY KEY REFERENCES AppliUserT(id) ON DELETE CASCADE,
    weekHourlyQuota INTEGER NOT NULL,
    yearHourlyQuota INTEGER NOT NULL,
    transportMode INTEGER NOT NULL REFERENCES Transportation(id),
    location INTEGER NOT NULL REFERENCES Location(id)
);

CREATE Table ManagerT (
    id INTEGER PRIMARY KEY REFERENCES InterpreterT(id) ON DELETE CASCADE
);

CREATE TABLE BeneficiaryT (
    id INTEGER PRIMARY KEY REFERENCES AppliUserT(id) ON DELETE CASCADE,
    status INTEGER NOT NULL REFERENCES Status(id),
    referenceInterpreter INTEGER NOT NULL REFERENCES InterpreterT(id)
);

CREATE TABLE TimeSlot (
    id INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    startDateTime DATE NOT NULL,
    endDateTime DATE NOT NULL
);

CREATE TABLE BaseTimeSlot (
    timeSlot INTEGER NOT NULL REFERENCES TimeSlot(id) ON DELETE CASCADE,
    day NUMBER(1) NOT NULL,
    CONSTRAINT PKBaseTimeSlot PRIMARY KEY (timeSlot, day)
);

CREATE TABLE Unavailability (
    interpreter INTEGER NOT NULL REFERENCES InterpreterT(id) ON DELETE CASCADE,
    punctualTimeSlot INTEGER NOT NULL REFERENCES TimeSlot(id),
    reason VARCHAR2(50 CHAR) NOT NULL,
    CONSTRAINT PKUnavailability PRIMARY KEY (interpreter, punctualTimeSlot)
);

CREATE TABLE Availability (
    interpreter INTEGER NOT NULL REFERENCES InterpreterT(id) ON DELETE CASCADE,
    baseTimeSlot INTEGER NOT NULL,
    baseTimeSlotDay NUMBER(1) NOT NULL,
    CONSTRAINT FKAvailability FOREIGN KEY (baseTimeSlot, baseTimeSlotDay) REFERENCES BaseTimeSlot (timeSlot, day),
    CONSTRAINT PKAvailability PRIMARY KEY (interpreter, baseTimeSlot, baseTimeSlotDay)
);

CREATE TABLE AcademicSkill (
    id INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    designation VARCHAR2(25 CHAR) NOT NULL UNIQUE
);

CREATE TABLE JobSkill (
    id INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    designation VARCHAR2(25 CHAR) NOT NULL UNIQUE
);

CREATE TABLE AcademicSkillInterpreter (
    interpreter INTEGER NOT NULL REFERENCES InterpreterT(id) ON DELETE CASCADE,
    skill INTEGER NOT NULL REFERENCES AcademicSkill(id) ON DELETE CASCADE,
    CONSTRAINT PKAcademicSkillInterpreter PRIMARY KEY (interpreter, skill)
);

CREATE TABLE JobSkillInterpreter (
    interpreter INTEGER NOT NULL REFERENCES InterpreterT(id) ON DELETE CASCADE,
    skill INTEGER NOT NULL REFERENCES JobSkill(id) ON DELETE CASCADE,
    CONSTRAINT PKJobSkillInterpreter PRIMARY KEY (interpreter, skill)
);

CREATE TABLE Mission (
    id INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    importance NUMBER(1) NOT NULL,
    subject VARCHAR2(50 CHAR) NOT NULL,
    commentary VARCHAR2(100 CHAR),
    location INTEGER NOT NULL REFERENCES Location(id),
    room VARCHAR2(25 CHAR)
);

CREATE TABLE MissionBeneficiary (
    mission INTEGER PRIMARY KEY REFERENCES Mission(id) ON DELETE CASCADE,
    beneficiary INTEGER NOT NULL REFERENCES BeneficiaryT(id) ON DELETE CASCADE,
    jobSkill INTEGER NOT NULL REFERENCES JobSkill(id),
    academicSkill INTEGER NOT NULL REFERENCES AcademicSkill(id)
);

CREATE TABLE MissionState (
    id NUMBER(1) PRIMARY KEY,
    name VARCHAR(15)
);
