CREATE TABLE PunctualMission (
    mission INTEGER NOT NULL REFERENCES Mission(id) ON DELETE CASCADE,
    punctualTimeSlot INTEGER NOT NULL REFERENCES timeSlot(id),
    stateOfMission NUMBER(1) NOT NULL REFERENCES MissionState(id),
    CONSTRAINT PKPunctualMission PRIMARY KEY (mission, punctualTimeSlot)
);

CREATE TABLE RegularMission (
    mission INTEGER NOT NULL REFERENCES Mission(id) ON DELETE CASCADE,
    baseTimeSlot INTEGER NOT NULL,
    baseTimeSlotDay NUMBER(1) NOT NULL,
    CONSTRAINT FKRegularMission FOREIGN KEY (baseTimeSlot, baseTimeSlotDay) REFERENCES BaseTimeSlot (timeSlot, day),
    CONSTRAINT PKRegularMission PRIMARY KEY (mission, baseTimeSlot, baseTimeSlotDay)
);

CREATE TABLE InterpreterMission (
    mission INTEGER NOT NULL,
    punctualTimeSlot INTEGER NOT NULL,
    interpreter INTEGER NOT NULL REFERENCES InterpreterT(id) ON DELETE CASCADE,
    CONSTRAINT FKInterpreterMission FOREIGN KEY (mission, punctualTimeSlot) REFERENCES PunctualMission (mission, punctualTimeSlot),
    CONSTRAINT PKInterpreterMission PRIMARY KEY (mission, interpreter)
);


