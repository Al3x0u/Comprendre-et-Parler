CREATE TABLE Mission (
    id INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    beneficiary INTEGER REFERENCES BeneficiaryT(id) ON DELETE CASCADE,
    importance NUMBER(1) DEFAULT 0 NOT NULL,
    subject VARCHAR2(50 CHAR) NOT NULL,
    stateOfMission NUMBER(1) DEFAULT 3 NOT NULL REFERENCES MissionState(id),
    commentary VARCHAR2(100 CHAR),
    timeSlot INTEGER NOT NULL REFERENCES TimeSlot(id),
    jobSkill INTEGER REFERENCES JobSkill(id),
    academicSkill INTEGER REFERENCES AcademicSkill(id),
    location INTEGER NOT NULL REFERENCES Location(id),
    room VARCHAR2(25 CHAR)
);

CREATE TABLE RegularMissionCancelled (
    mission INTEGER NOT NULL REFERENCES Mission(id) ON DELETE CASCADE,
    numWeek NUMBER(2) NOT NULL,
    CONSTRAINT PKRegularMissionCancelled PRIMARY KEY (mission, numWeek)
);

CREATE TABLE InterpreterMission (
    mission INTEGER NOT NULL REFERENCES Mission(id) ON DELETE CASCADE,
    interpreter INTEGER NOT NULL REFERENCES InterpreterT(id) ON DELETE CASCADE,
    CONSTRAINT PKInterpreterMission PRIMARY KEY (mission, interpreter)
);


